//! # smux v1 握手协议规范（sans-IO）
//!
//! 本模块定义 smux v1 在**连接建立阶段**的握手协商流程与线格式（wire
//! format）。它只负责在一条已经建立好的、可靠且有序的字节流上交换握手帧，
//! 并产出一份双方一致的 [`opts::HandshakeOpts`]。字节流的建立、加密、认证，
//! 以及握手完成后的 channel/数据帧格式、分片与心跳，均不属于本模块的职责。
//!
//! 本文件是规范正文。实现代码时，凡使用「必须」、「禁止」描述的行为都是协议
//! 约束，不得自行放宽。尚未定稿的实现取舍见仓库根目录的
//! `dev-notes.md`（仓库根目录）。
//!
//! ## 1. 范围与角色
//!
//! 握手有两个角色，由调用方决定，而非由协议区分：
//!
//! - **发起方（Initiator）**：先发送 `INVITE` 的一方，对应 §8.1 与 §12。
//! - **等待方（Responder）**：先接收 `INVITE` 的一方，对应 §8.2 与 §12。
//!
//! 一次完整的握手最多交换 4 个帧：
//!
//! ```text
//! Initiator                                              Responder
//!     |                                                       |
//!     |------------------ INVITE --------------------------->|
//!     |                                                       |
//!     |<----------------- ACCEPT (或 REJECT) ----------------|
//!     |                                                       |
//!     |------------------ CONFIRM -------------------------->|
//!     |                                                       |
//!     |<----------------- CONFIRM (或 REJECT) ---------------|
//!     |                                                       |
//! ```
//!
//! 任一方发送或接收 `REJECT`，或任一校验失败，握手立即失败，双方必须关闭底层
//! 传输，不得在该连接上继续发送任何握手帧或数据帧。
//!
//! ## 2. 术语
//!
//! | 术语 | 含义 |
//! | --- | --- |
//! | 帧（Frame） | 一次握手消息的完整字节序列，见 §4 |
//! | 条目（Entry） | 帧内的一个自描述 TLV，见 §6 |
//! | 条目区 | `算法预告` 之后、`校验头` 之前的全部条目 |
//! | 算法预告 | `magic` 之后的 1 字节，提前声明本帧的 CRC 算法，见 §4.2 |
//! | 校验头（Checksum header） | 帧尾 1 字节，标识 CRC 值的开始，见 §6.2 |
//! | 基础项（Basic option） | [`opts::NegotiationKey`] 中 `0x00..=0x03` 四项，映射到 [`opts::BasicOpts`] 的 4 个字段 |
//! | 规范化编码 | 用能容纳该数值的最小 `val_type` 宽度进行编码 |
//!
//! ## 3. 全局约定
//!
//! - 所有多字节整数一律为**大端序**（network byte order），且均为无符号数。
//! - 帧内条目的顺序不承载语义（除重复键检测外）；实现必须能处理任意合法顺序。
//! - 帧的完整性由 **CRC 值**保证。算法被声明**两次**：`magic` 之后的
//!   **算法预告**（让接收方一开始就能选定算法、边读边算），以及帧尾的
//!   **校验头**（定界符，让接收方知道 `crc` 从哪一字节开始）。两处取值
//!   **必须一致**，见 §4。
//! - 只允许 CRC-16/XMODEM（2 字节）、CRC-24/BLE（3 字节）或 CRC-32/ISO-HDLC
//!   （4 字节）。**每帧自行声明算法，不要求同一连接内的各帧使用同一种算法。**
//! - 数据帧的校验算法**不参与**握手协商，不属于本模块的范围。
//! - 握手帧**不携带长度字段**：帧的结束位置由**校验头**确定（见 §4）——
//!   正因为条目区没有长度、也没有显式结束标记，帧尾那个 1 字节校验头是
//!   不可省略的定界符。
//! - **条目数量不设上限**：理论上可以有任意多个条目。因此实现**不得**以
//!   「帧长上限」为前提，也不得预留承载整帧的缓冲；防御无界连接是调用方的
//!   职责（见 §10）。
//! - no_std、无堆分配：实现不得依赖 `alloc`；校验以**逐字节增量**方式计算，
//!   见 §11。
//!
//! ## 4. 帧格式
//!
//! 帧 = `magic(4 字节)` + `算法预告(1 字节)` + `条目区（0 个或多个条目）` +
//! `校验头(1 字节)` + `crc(2/3/4 字节)`。
//!
//! 帧**没有长度字段**：条目区没有长度、也没有显式结束标记，因此帧尾的
//! **校验头**是必不可少的定界符——接收方靠它判断「条目区到此结束、接下来是
//! CRC 值」。算法则被声明**两次**（预告 + 校验头），原因见 §4.3。
//!
//! ```text
//! +--------------------------------------------------------------+
//! |                         magic (4 B)                          |
//! +--------------+-----------------------------------------------+
//! | alg (1 B)    |             entry #0 ...                      |
//! | 1C/2C/3C     |                                               |
//! +--------------+                                               :
//! :                                                              :
//! +--------------+-----------------------------------------------+
//! | chksum hdr   |            crc (2/3/4 B, BE)                  |
//! | 1C/2C/3C     |                                               |
//! +--------------+-----------------------------------------------+
//! ```
//!
//! | 偏移 | 长度 | 字段 | 说明 |
//! | --- | --- | --- | --- |
//! | `0` | 4 | `magic` | 见 §5；标识消息类型 |
//! | `4` | 1 | `alg` | 校验算法**预告**，见 §4.2 |
//! | `5` | 变长 | `entry` | 0 个或多个条目，见 §6；可为空 |
//! | 帧尾 | 1 | `checksum hdr` | **校验头**，取值与 `alg` 相同，见 §6.2 |
//! | 帧尾 +1 | 2/3/4 | `crc` | CRC 值，大端；长度由 `alg` 决定 |
//!
//! **CRC 覆盖范围**：从 `magic` 首字节起，到 `crc` 之前的**全部**字节
//! （含 `alg` 与 `checksum hdr`）。`crc` 自身不参与计算。
//!
//! ### 4.1 三个字节字段的关系
//!
//! `alg`（帧首）与 `checksum hdr`（帧尾）是**同一个字节的两种角色**，编码也
//! 完全一致（高半字节 `val_type` 给出算法与 `crc` 长度，低半字节固定为键
//! `0x0C`），因此取值范围同为下表三种：
//!
//! | 取值 | 高半字节 | CRC 算法 | `crc` 长度 |
//! | --- | --- | --- | --- |
//! | `0x1C` | `0x1`（`BeU16`） | CRC-16/XMODEM | 2 字节 |
//! | `0x2C` | `0x2`（`BeU24`） | CRC-24/BLE | 3 字节 |
//! | `0x3C` | `0x3`（`BeU32`） | CRC-32/ISO-HDLC | 4 字节 |
//!
//! - `alg` 取值非法 → `UnsupportedOption`，**立即终止**（此时既不知道 `crc`
//!   长度，也无法定位帧尾，不能继续读）。
//! - `checksum hdr` 取值非法 → `UnsupportedOption`（见 §6.2）。
//! - **两者必须一致**：若 `checksum hdr` 与 `alg` 声明的算法不同，接收方
//!   **必须**以 `MalformedBody` 拒绝该帧，不得按其中一个继续解析。发方
//!   **必须**发送一致的两个字节。
//!
//! ### 4.2 算法预告字节（帧首 `alg`）
//!
//! **作用**：接收方读完 `magic` 就知道本帧用哪种算法，可以从 `alg` 这一字节
//! 开始**边读边增量计算** CRC，无需为「算法到帧尾才揭晓」而同时维护多个候选
//! 校验状态（见 §11）。
//!
//! ### 4.3 校验头字节（帧尾 `checksum hdr`）
//!
//! **作用**：**定界符**。条目区既无长度也无结束标记，只有读到这个 1 字节、
//! 确认它是合法的校验头，接收方才知道「条目区结束、接下来读 2/3/4 字节
//! `crc`」。因此**它不可省略**——只靠帧首预告无法判断何时停止读条目。
//!
//! 预告与校验头分工不同、都不能省：
//!
//! | 字段 | 位置 | 作用 |
//! | --- | --- | --- |
//! | `alg` | `magic` 之后 | 让校验**能增量起步** |
//! | `checksum hdr` | 帧尾 | 让条目区**有确定终点** |
//!
//! ### 4.4 读取算法（必须严格遵守）
//!
//! 1. 读满 4 字节 `magic`，同时把它计入 CRC；
//! 2. 读 1 字节 `alg`，据此选定校验算法与 `crc` 长度，并把 `alg` 计入 CRC；
//!    取值非法 → `UnsupportedOption`，立即终止；
//! 3. 循环读取条目：
//!    1. 读 1 字节 `header`，计入 CRC；
//!    2. 若 `key == Checksum(0x0C)`：进入第 4 步；
//!    3. 否则按 §6 的宽度规则解析该条目；若键不是本版本认识的键 →
//!       `UnsupportedOption` 并终止；把该条目的全部字节计入 CRC，回到 3.1；
//! 4. 校验 `checksum hdr`：取值必须是 `alg` 允许的三种之一，且**必须与 `alg`
//!    一致**（见 §4.1），否则 `UnsupportedOption` / `MalformedBody`；把该字节
//!    计入 CRC；
//! 5. 读满 `crc`（2、3 或 4 字节，由 `alg` 决定），与增量计算出的值比较；
//!    不等 → `ChecksumErr`；相等则本帧结束，其后的字节属于下一帧。
//!
//! **协商与校验的关系**：条目在读到时就逐条交给协商方判断（见 §11、§12），
//! **不必等整帧**；CRC 则在帧尾才比较，且**一票否决**——校验失败时整次协商
//! 结果作废，握手失败（见 §9）。协商方看不到校验值，也不参与校验。
//!
//! **没有 `max_size`**：条目数量不设上限（见 §3），因此不存在「单帧总字节数
//! 上限」这一保护。防御无界连接由调用方的取消令牌负责（见 §10）；本端对
//! **单个条目长度**的内部上限属于实现策略，见 §11。
//!
//! ## 5. 消息类型
//!
//! | 常量 | 字节（十六进制） | 方向 | 条目区内容 |
//! | --- | --- | --- | --- |
//! | [`K_INVITE_MAGIC`] | `5F 1B 01 69` | 发起方 → 等待方 | 发起方的协商条目，可为空 |
//! | [`K_ACCEPT_MAGIC`] | `5F 1B 01 41` | 等待方 → 发起方 | 补全后的完整协商结果，**必须**含全部 4 个基础项 |
//! | [`K_CONFRM_MAGIC`] | `5F 1B 01 63` | 双向 | 发起方：完整协商结果；等待方：**空** |
//! | [`K_REJECT_MAGIC`] | `5F 1B 01 4A` | 双向 | v1 **必须**为空 |
//!
//! 四种消息都固定带有 §4 的算法预告、帧尾校验头与 `crc`；「条目区为空」指
//! `magic` 与算法预告之后**直接就是**帧尾的 `checksum hdr` 与 `crc`。
//! `magic` 的 `5F 1B 01` 前缀用于快速识别 smux v1 握手帧，末字节区分类型。
//!
//! ## 6. 条目（TLV）编码
//!
//! 条目区由若干条目顺序拼接而成，每个条目自描述、可变长：
//!
//! ```text
//! +--------+-------------------------------+
//! | header | value ...                     |
//! | 1 B    | W B                           |
//! +--------+-------------------------------+
//!
//! header = (val_type << 4) | key
//! ```
//!
//! - `key = header & 0x0F`，取值见 [`opts::NegotiationKey`]。
//! - `val_type = (header & 0x70) >> 4`，取值见 [`opts::NegotiationValType`]；
//!   决定 `value` 的字节数 `W`：
//!
//! | `val_type` | 枚举 | `W` | 可表示范围 |
//! | --- | --- | --- | --- |
//! | `0x0` | `BeU8` | 1 | `0..=2^8-1` |
//! | `0x1` | `BeU16` | 2 | `0..=2^16-1` |
//! | `0x2` | `BeU24` | 3 | `0..=2^24-1` |
//! | `0x3` | `BeU32` | 4 | `0..=2^32-1` |
//! | `0x4` | `BeU64` | 8 | `0..=2^64-1` |
//!
//! - `value` 为 `W` 字节大端无符号整数，解码后以 `usize` 承载；32 位平台上
//!   无法容纳的取值必须报错（`MalformedBody`，见 §9），不得截断。
//! - **规范化编码**：发送方**必须**选择能容纳该数值的最小 `val_type` 宽度；
//!   接收方**必须**接受任意足够宽的编码（不得因宽度不同而拒绝）。
//! - `header` 的 bit 7 为保留位，发送方**必须**置 0；接收方解析时按 `0x70`
//!   掩码取值，天然忽略该位。
//!
//! ### 6.1 基础条目
//!
//! `key ∈ {0x00, 0x01, 0x02, 0x03}` 时，`value` 是上表定义的定长整数，语义见
//! §7。对应 Rust 类型 [`opts::NegotiationBasicEntry`]：`opts_key` 保存完整
//! `header` 字节（含 `val_type`），`val_data` 保存解码后的数值。
//!
//! ### 6.2 校验键（`key == Checksum == 0x0C`）
//!
//! 校验键**不是**协商项。它的头字节编码（高半字节 `val_type` 表示算法，低半
//! 字节固定为 `0x0C`）在帧中出现**三处**，其中前两处是**同一个头字节**：
//!
//! | 位置 | 形式 | 作用 |
//! | --- | --- | --- |
//! | 帧首、`magic` 之后 1 字节 | **算法预告** | 让接收方能**增量起步**计算校验，见 §4.2 |
//! | 帧尾 1 字节 | **校验头** | **定界符**：宣告条目区结束、`crc` 开始，见 §4.3 |
//! | 帧尾 +1，2/3/4 字节 | `crc` 值 | 裸的大端数值，长度由算法预告决定 |
//!
//! 帧尾校验头的线格式：
//!
//! ```text
//! +---------------+---------------------------+
//! | header (1 B)  | crc (2/3/4 B, BE)         |
//! +---------------+---------------------------+
//! ```
//!
//! - 头字节取值与算法预告相同，只允许 §4.1 表中的三种；其它取值（含 CRC-8
//!   `0x0C`、CRC-64 `0x4C`）一律**非法** → `UnsupportedOption`。
//! - **校验头必须与算法预告一致**：不一致 → `MalformedBody`（见 §4.1）。
//! - 校验头**必须恰好出现一次且位于帧尾**，不得出现在其它条目中间。解析器
//!   一旦读到 `Checksum` 键即结束条目区。
//! - `crc` 以**大端**写入（2、3 或 4 字节，由算法预告决定），覆盖范围见 §4。
//! - **帧的结尾就是 `crc` 的最后一个字节**：这是 v1 的不兼容边界，未来任何
//!   允许帧在 `crc` 之后继续的扩展都会与 v1 不兼容。
//!
//! ### 6.3 保留键与非法键
//!
//! 除基础键（`0x00..=0x03`）与校验键（`0x0C`）外，其余键（含保留段
//! `0x04..=0x0B`、`0x0D..=0x0F`）在 v1 中一律**非法**。发送方**禁止**发送；
//! 接收方遇到即 `UnsupportedOption`，必须拒绝该帧。同一帧内同一已知 `key`
//! 出现两次 → `MalformedBody`。
//!
//! ## 7. 协商流程
//!
//! 协商**不是**双方的自动取小或自动合并：收到对端条件后，由**上层调用者**决定
//! 是否接受。上层拒绝（例如某个取值超出本端能力）时，直接发送 `REJECT` 并终止
//! 握手。
//!
//! ### 7.1 四项基础项
//!
//! | `key` | [`opts::BasicOpts`] 字段 | 含义 | 合法范围 |
//! | --- | --- | --- | --- |
//! | `0x00` `MaxPacketSize` | `max_packet_size` | 单个报文最大字节数（含头部） | `>= 1` |
//! | `0x01` `MaxChannelCount` | `max_channel_count` | 单连接最大同时活动 channel 数 | `>= 1` |
//! | `0x02` `MaxDockChanCount` | `max_dock_chan_count` | 单 dock 最大同时活动 channel 数 | `>= 1` |
//! | `0x03` `MaxChannelTimeout` | `max_channel_timeout` | channel 无数据后的最长存活秒数 | `>= 1` |
//!
//! 缺省值取 [`opts::BasicOpts::DEFAULT`]。任一项取值为 `0` → `MalformedBody`。
//!
//! `INVITE` 中的基础项就是发起方希望使用的取值。发起方**可以**只列出部分基础
//! 项；未列出的项由等待方按 §7.2 补全。
//!
//! ### 7.2 等待方的补全与决策（收到 `INVITE` 后）
//!
//! 等待方按以下规则生成**完整结果** `result`：
//!
//! 1. 对 `INVITE` 中**已提及**的基础项，逐字采用发起方的取值；
//! 2. 对 `INVITE` 中**未提及**的基础项，用本端取值补全（缺省为
//!    [`opts::BasicOpts::DEFAULT`]）。
//!
//! 随后把 `result` 交给上层调用者决策：
//!
//! - **接受** → 发送 `ACCEPT`，条目区**必须恰好包含全部 4 个基础项各一次**，
//!   数值为 `result[K]`。
//! - **拒绝**（例如发起方的某项取值超出本端能力）→ 发送 `REJECT` 并终止握手。
//!
//! 推荐按 `key` 升序编码，但接收方不得依赖顺序。
//!
//! ### 7.3 发起方的确认与决策（收到 `ACCEPT` 后）
//!
//! 1. `magic == K_ACCEPT_MAGIC`；若为 [`K_REJECT_MAGIC`] 则判定握手失败，其它
//!    值 → `InvalidMagic`。
//! 2. 帧级 CRC 校验已在 §4 的读取阶段完成，失败即 `ChecksumErr`。
//! 3. 条目区中基础项必须**恰好 4 个且不重复**，否则 `MalformedBody`。
//! 4. 把完整结果交给上层调用者决策：
//!    - **接受** → 发送 `CONFIRM`，条目区为这 4 个基础项；数值必须与 `ACCEPT`
//!      完全相同，**编码宽度可以不同**（按数值比较）。
//!    - **拒绝** → 发送 `REJECT` 并终止握手。
//!
//! ### 7.4 等待方的提交校验（收到 `CONFIRM` 后）
//!
//! 1. `magic == K_CONFRM_MAGIC`，帧级 CRC 已通过。
//! 2. 条目区中基础项必须**恰好 4 个且不重复**，且每项数值等于本端 `ACCEPT`
//!    中的 `result[K]`（编码宽度任意）。
//! 3. 全部一致 → 发送条目区为空（`magic` 与算法预告之后直接跟 `checksum hdr`
//!    与 `crc`）的 `CONFRM`，握手成功；否则发送 `REJECT` 并关闭传输。
//!
//! ### 7.5 `REJECT`
//!
//! - 触发点：§7.2、§7.3 的上层拒绝，或 §7.4 第 2 步校验失败。
//! - v1 的 `REJECT` 条目区**必须为空**，不携带任何原因码；算法预告与 CRC
//!   照常带上。
//! - 协商方在**读到一半**就拒绝时，**不再读剩余条目**，立即发送 `REJECT`
//!   并关闭传输（见 §9、§11）。
//! - 收到或发送 `REJECT` 后，双方**必须**关闭底层传输，不得重试同一次握手。
//!
//! ## 8. 状态机
//!
//! ### 8.1 发起方
//!
//! ```text
//! [Init] --发送 INVITE--> [AwaitAccept]
//!
//! [AwaitAccept]
//!   ├ 收到合法 ACCEPT 且 §7.3 通过、上层接受
//!   │     --发送 CONFIRM--> [AwaitPeerConfirm]
//!   ├ 上层拒绝 --发送 REJECT--> [Failed]
//!   └ 收到 REJECT / 校验失败 --> [Failed]
//!
//! [AwaitPeerConfirm]
//!   ├ 收到条目区为空的 CONFRM --> [Established]
//!   └ 其它 / 校验失败         --> [Failed]（按需发 REJECT 后关闭）
//! ```
//!
//! ### 8.2 等待方
//!
//! ```text
//! [Init]
//!   ├ 收到合法 INVITE、上层接受 --发送 ACCEPT--> [AwaitConfirm]
//!   ├ 收到合法 INVITE、上层拒绝 --发送 REJECT--> [Failed]
//!   └ 收到非法 INVITE ------------------------> [Failed]（按需发 REJECT 后关闭）
//!
//! [AwaitConfirm]
//!   ├ §7.4 通过 --发送空 CONFRM--> [Established]
//!   └ §7.4 失败 --发送 REJECT----> [Failed]
//! ```
//!
//! ### 8.3 时序约束
//!
//! - 握手帧严格按序，不得交错；任一端同一时刻最多有一个未完成的握手帧。
//! - 双方都不得在握手完成前发送任何数据帧。
//! - 若对端在读满一个帧之前关闭（`is_drained_closing()` 为真，或
//!   [`ReadErrTag::Closing`](abs_buff::error::ReadErrTag::Closing)）→
//!   `PeerClosed`，握手失败。
//!
//! ## 9. 错误分类
//!
//! | 变体 | 触发条件 | 处置 |
//! | --- | --- | --- |
//! | `Cancelled` | 取消令牌触发 | 终止并关闭传输；不回帧 |
//! | `RxErr(R::Err)` | 底层读错误 | 透传 |
//! | `TxErr(W::Err)` | 底层写错误 | 透传 |
//! | `InvalidMagic` | 首 4 字节不是本状态期望的 magic | 终止；不回帧 |
//! | `ChecksumErr` | CRC 不匹配 | 终止；错误帧不回帧 |
//! | `MalformedBody` | 宽度越界、重复键、校验头与算法预告不一致、单条目长度超过本端内部上限等 | 终止；不回帧 |
//! | `UnsupportedOption` | 算法预告或校验头取值非法、未知或保留键 | 终止；立即关闭传输 |
//! | `Inconsistent` | `ACCEPT` / `CONFIRM` 与预期不符 | 发 `REJECT` |
//! | `PeerClosed` | 帧中途对端关闭 | 终止 |
//!
//! **协商未通过 → 立即发 `REJECT`，且不再读完剩余条目**（见 §7）。校验是
//! 一票否决：即使协商已经通过，校验失败仍以 `ChecksumErr` 终止整次握手，且
//! 不回帧。
//!
//! **算法预告非法是特殊情形**：此时既无法确定 `crc` 长度，也无法定位帧尾，
//! 因此必须立即终止并关闭传输，不能「发个 REJECT 再继续读」。
//!
//! **校验头与预告不一致**：两个字节各自合法但声明不同算法时，帧的边界仍可按
//! 预告确定，但语义自相矛盾，因此按 `MalformedBody` 拒绝、不回帧。
//!
//! ## 10. 取消与超时
//!
//! - 所有异步原语**必须**通过 `may_cancel_with(cancel)` 支持主动取消；对外
//!   公开的异步方法**应当**用 `gen_may_cancel_future` 封装（见 AGENTS.md
//!   纪律 4）。
//! - 取消发生在帧中途时，已读字节无法安全回退，本次握手**必须**判定失败并
//!   关闭传输；v1 **不提供**断点续读。
//! - 模块自身不实现超时；超时由调用方通过 cancel token 施加。
//!
//! ## 11. 实现要点（abs_buff 适配）
//!
//! - **流式解析**：私有 `codec` 模块按字段顺序读 `TrBuffRead`：先 4 字节
//!   `magic`，再 1 字节算法预告，然后**逐个条目**读 `header` 与 `value`，
//!   读到校验键即转入帧尾，读 1 字节校验头与 2/3/4 字节 `crc`。没有
//!   「缓冲不足就返回还需多少字节」的中间状态，也不需要调用方提供长度已知的
//!   整帧缓冲区。
//! - **单趟增量校验**：算法预告出现得足够早，因此**只维护一个**校验状态：
//!   从 `magic` 起把每个读到的字节依次喂进去（含算法预告与校验头），到帧尾
//!   `finalize` 与 `crc` 比较。不需要「同时开多个候选 CRC」，也不需要保存
//!   整帧。
//! - **两个算法字节的一致性检查**：校验头读到后，实现必须与先前记下的预告
//!   比较；不一致即 `MalformedBody`（§4.1）。
//! - **逐条目内存**：实现**不累积条目**。基础项解码进 4 个定长槽位；扩展项把
//!   负载长度与负载本身交给协商方后即可丢弃。本端对**单个条目长度**设有内部
//!   上限（实现策略，不是协议的一部分，见 §3）：读负载**之前**先校验声明长度，
//!   超限即拒绝，从而不必为恶意长度预留缓冲。
//! - **条目数量无界**：因为不累积条目、也不预留整帧缓冲，条目数量不设上限
//!   不会导致本端内存增长；防御无界连接由调用方的取消令牌负责（见 §10）。
//! - **协商即时报文**：条目在**读到的那一刻**交给协商方（§12）；协商方可以
//!   立即拒绝，此时**不再读剩余条目**，直接回 `REJECT`（§9）。
//! - **写侧**：`TrBuffTryWrite::try_write` 借出 `SegmMut<u8>`，通过
//!   `as_segm_mut().clone_items_from_buff(..)` 写入，`Drop` 时按写入量提交。
//!   校验同样可以增量计算，因此写侧也不需要先把整帧成形在缓冲里。
//! - **读侧**：用 `TrBuffTryRead::try_read` 借出段并按需复制；段被回收时把
//!   消费量记回底层缓冲，因此可以分多次读满一个字段。
//! - **取消**：读侧在每次重试前检查取消令牌；写侧由上层 future 统一在
//!   `may_cancel_with(cancel)` 下推进。协商方中途拒绝导致的「写一半收到
//!   REJECT」不是需要特殊处理的错误，按底层写错误处理即可。
//!
//! ## 12. 对外接口
//!
//! 握手对外只暴露一个对象与它交付的结果：
//!
//! - [`agent::HandshakeAgent`]：同时承载发起方与等待方两种角色；
//!   [`agent::HandshakeAgent::invite_async`] 执行发起方流程，
//!   [`agent::HandshakeAgent::listen_async`] 执行等待方流程。
//! - 协商策略由 [`agent::TrNegotiator`] 提供：条目**边读边交**给它，由它决定
//!   接受还是立即拒绝。
//! - 成功后交付 [`agent::HandshakeDelivery`]：协商规格
//!   （[`opts::HandshakeOpts`]）与归还的一对 `Tx` / `Rx`。
//! - 失败类型为 [`error::HandshakeError`]。
//!
//! 其余编解码、成帧与状态机实现均为私有。

pub mod agent;
pub mod error;
pub mod opts;

mod codec_;

pub use codec_::HandshakeChecksum;

const MAGIC_FIELD_SIZE: usize = 4;
type MagicField = [u8; MAGIC_FIELD_SIZE];

/// `INVITE` 帧的 magic：`5F 1B 01 69`。
///
/// 发起方发送的第一帧，携带其协商条目，见模块级文档 §5。
pub const K_INVITE_MAGIC: MagicField = [95, 27, 1, b'i'];

/// `ACCEPT` 帧的 magic：`5F 1B 01 41`。
///
/// 等待方对 `INVITE` 的接受应答，条目区为补全后的完整协商结果，见 §5 与 §7.2。
pub const K_ACCEPT_MAGIC: MagicField = [95, 27, 1, b'A'];

/// `REJECT` 帧的 magic：`5F 1B 01 4A`。
///
/// 协商失败时由任一方发送；v1 的条目区必须为空，见 §7.5。
pub const K_REJECT_MAGIC: MagicField = [95, 27, 1, b'J'];

/// `CONFRM` 帧的 magic：`5F 1B 01 63`。
///
/// 发起方用它提交完整协商结果；等待方用它发送空条目区的最终确认，见 §5。
pub const K_CONFRM_MAGIC: MagicField = [95, 27, 1, b'c'];
