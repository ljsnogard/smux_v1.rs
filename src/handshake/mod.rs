//! # smux v1 握手协议规范（sans-IO）
//!
//! 本模块定义 smux v1 在**连接建立阶段**的握手协商流程与线格式（wire
//! format）。它只负责在一条已经建立好的、可靠且有序的字节流上交换握手帧，
//! 并产出一份双方一致的 [`opts::HandshakeOpts`]。字节流的建立、加密、认证，
//! 以及握手完成后的 channel/数据帧格式、分片与心跳，均不属于本模块的职责。
//!
//! 本文件是规范正文。实现代码时，凡使用「必须」、「禁止」描述的行为都是协议
//! 约束，不得自行放宽。尚未定稿的实现取舍见仓库根目录的
//! `dev-progress-notes.md`。
//!
//! ## 1. 范围与角色
//!
//! 握手有两个角色，由调用方决定，而非由协议区分：
//!
//! - **发起方（Initiator）**：先发送 `INVITE` 的一方，对应 §8.1 与 §12。
//! - **等待方（Responder）**：先接收 `INVITE` 的一方，对应 §8.2 与 §12。
//!
//! 一次完整的握手最多交换 4 个帧：
//!
//! ```text
//! Initiator                                              Responder
//!     |                                                       |
//!     |------------------ INVITE --------------------------->|
//!     |                                                       |
//!     |<----------------- ACCEPT (或 REJECT) ----------------|
//!     |                                                       |
//!     |------------------ CONFIRM -------------------------->|
//!     |                                                       |
//!     |<----------------- CONFIRM (或 REJECT) ---------------|
//!     |                                                       |
//! ```
//!
//! 任一方发送或接收 `REJECT`，或任一校验失败，握手立即失败，双方必须关闭底层
//! 传输，不得在该连接上继续发送任何握手帧或数据帧。
//!
//! ## 2. 术语
//!
//! | 术语 | 含义 |
//! | --- | --- |
//! | 帧（Frame） | 一次握手消息的完整字节序列，见 §4 |
//! | 条目（Entry） | 帧内的一个自描述 TLV，见 §6 |
//! | 条目区 | 校验尾之前、`magic` 之后的全部条目，即通常所说的 body |
//! | 基础项（Basic option） | [`opts::NegotiationKey`] 中 `0x00..=0x03` 四项，映射到 [`opts::BasicOpts`] 的 4 个字段 |
//! | 校验尾（Checksum trailer） | 以 `Checksum` 键标识、携带 CRC 的帧尾条目，见 §6.2 |
//! | 规范化编码 | 用能容纳该数值的最小 `val_type` 宽度进行编码 |
//!
//! ## 3. 全局约定
//!
//! - 所有多字节整数一律为**大端序**（network byte order），且均为无符号数。
//! - 帧内条目的顺序不承载语义（除校验尾必须位于末尾、以及重复键检测外）；
//!   实现必须能处理任意合法顺序。
//! - 帧的完整性由**校验尾**保证，算法在其头字节中声明：只允许 CRC-16/XMODEM
//!   （2 字节）或 CRC-32/ISO-HDLC（4 字节），见 §6.2。**每帧自行声明算法，不
//!   要求同一连接内的各帧使用同一种算法。**
//! - 数据帧的校验算法**不参与**握手协商，不属于本模块的范围。
//! - 握手帧**不携带长度字段**：帧的结束位置由校验尾条目确定（见 §4）。
//! - no_std、无堆分配：实现不得依赖 `alloc`；CRC 必须增量计算，见 §11。
//!
//! ## 4. 帧格式
//!
//! 帧 = `magic(4 字节)` + `条目区（0 个或多个条目）` + `校验尾条目`。
//! 校验尾**必须**是整个帧的最后一个条目；解析器一旦读到 `Checksum` 键，帧即
//! 结束。
//!
//! ```text
//! +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
//! |                          magic (4 B)                         |
//! +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
//! |  entry #0 ...                                                |
//! :                                                              :
//! +-+-+-+-+-+-+-+-+ +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
//! | checksum hdr  | |        crc (2 或 4 B, BE)                  |
//! | 0x1C / 0x2C   | |                                           |
//! +-+-+-+-+-+-+-+-+ +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
//! |<------------ CRC 覆盖区（不含 crc 本身）-------------------->|
//! ```
//!
//! | 偏移 | 长度 | 字段 | 说明 |
//! | --- | --- | --- | --- |
//! | `0` | 4 | `magic` | 见 §5；标识消息类型 |
//! | `4` | 变长 | `entry` | 0 个或多个条目，见 §6；可为空 |
//! | 帧尾 | 1 | `checksum hdr` | `0x1C`（CRC-16）或 `0x2C`（CRC-32） |
//! | 帧尾 +1 | 2 或 4 | `crc` | 由头字节决定的 CRC，大端 |
//!
//! **CRC 覆盖范围**：从 `magic` 首字节起，直到 `crc` 之前（含校验尾头字节）
//! 的全部字节。`crc` 自身不参与计算。
//!
//! **读取算法（必须严格遵守）**：
//!
//! 1. 读满 4 字节 `magic`，同时把它计入 CRC 与帧长；
//! 2. 循环读取条目：
//!    1. 读 1 字节 `header`，计入 CRC 与帧长；
//!    2. 若 `key == Checksum(0x0C)`：进入第 3 步；
//!    3. 否则按 §6 的宽度规则解析该条目；若键不是本版本认识的基础键 →
//!       `UnsupportedOption` 并终止，把其全部字节计入 CRC 与帧长，回到 2.1；
//!    4. 若累计帧长超过 `max_size` → `FrameTooLarge`，必须**立即终止**，不得
//!       继续按条目的声明长度读取；
//! 3. 校验校验尾头：取值必须为 `0x1C` 或 `0x2C`；其它值 →
//!    `UnsupportedOption`；
//! 4. 读满对应长度的 `crc`（2 或 4 字节），与累计的 CRC 比较；不等 →
//!    `ChecksumErr`；相等则本帧结束，其后的字节属于下一帧。
//!
//! `max_size` 由**调用方**决定：发起握手或监听握手的一方在调用时传入。它表示
//! **单帧总字节数上限**，包含 `magic`、条目区与校验尾。由于帧没有显式长度
//! 字段，`max_size` 是防止无界读取的唯一保护。推荐取值与
//! [`opts::BasicOpts::max_packet_size`] 相同。
//!
//! ## 5. 消息类型
//!
//! | 常量 | 字节（十六进制） | 方向 | 条目区内容 |
//! | --- | --- | --- | --- |
//! | [`K_INVITE_MAGIC`] | `5F 1B 01 69` | 发起方 → 等待方 | 发起方的协商条目，可为空 |
//! | [`K_ACCEPT_MAGIC`] | `5F 1B 01 41` | 等待方 → 发起方 | 补全后的完整协商结果，**必须**含全部 4 个基础项 |
//! | [`K_CONFRM_MAGIC`] | `5F 1B 01 63` | 双向 | 发起方：完整协商结果；等待方：**空** |
//! | [`K_REJECT_MAGIC`] | `5F 1B 01 4A` | 双向 | v1 **必须**为空 |
//!
//! 四种消息都固定带有 §4 的校验尾；「条目区为空」指 `magic` 之后紧接校验尾。
//! `magic` 的 `5F 1B 01` 前缀用于快速识别 smux v1 握手帧，末字节区分类型。
//!
//! ## 6. 条目（TLV）编码
//!
//! 条目区由若干条目顺序拼接而成，每个条目自描述、可变长：
//!
//! ```text
//! +--------+-------------------------------+
//! | header | value ...                     |
//! | 1 B    | W B                           |
//! +--------+-------------------------------+
//!
//! header = (val_type << 4) | key
//! ```
//!
//! - `key = header & 0x0F`，取值见 [`opts::NegotiationKey`]。
//! - `val_type = (header & 0x30) >> 4`，取值见 [`opts::NegotiationValType`]；
//!   决定 `value` 的字节数 `W`：
//!
//! | `val_type` | 枚举 | `W` | 可表示范围 |
//! | --- | --- | --- | --- |
//! | `0x0` | `BeU8` | 1 | `0..=2^8-1` |
//! | `0x1` | `BeU16` | 2 | `0..=2^16-1` |
//! | `0x2` | `BeU32` | 4 | `0..=2^32-1` |
//! | `0x3` | `BeU64` | 8 | `0..=2^64-1` |
//!
//! - `value` 为 `W` 字节大端无符号整数，解码后以 `usize` 承载；32 位平台上
//!   无法容纳的取值必须报错，不得截断（见 §13）。
//! - **规范化编码**：发送方**必须**选择能容纳该数值的最小 `val_type` 宽度；
//!   接收方**必须**接受任意足够宽的编码（不得因宽度不同而拒绝）。
//! - `header` 的 bit 6、bit 7 为保留位，发送方**必须**置 0；接收方解析时
//!   按 `0x30` 掩码取值，天然忽略这两个位。
//!
//! ### 6.1 基础条目
//!
//! `key ∈ {0x00, 0x01, 0x02, 0x03}` 时，`value` 是上表定义的定长整数，语义见
//! §7。对应 Rust 类型 [`opts::NegotiationBasicEntry`]：`opts_key` 保存完整
//! `header` 字节（含 `val_type`），`val_data` 保存解码后的数值。
//!
//! ### 6.2 校验尾条目（`key == Checksum == 0x0C`）
//!
//! 校验尾**不是**协商项，而是帧的定界符与完整性校验：
//!
//! ```text
//! +---------------+---------------------------+
//! | header (1 B)  | crc (2 或 4 B, BE)        |
//! +---------------+---------------------------+
//! ```
//!
//! - 头字节只允许两种取值：
//!
//! | 头字节 | 高半字节 | CRC 算法 | `crc` 长度 |
//! | --- | --- | --- | --- |
//! | `0x1C` | `0x1`（`BeU16`） | CRC-16/XMODEM | 2 字节 |
//! | `0x2C` | `0x2`（`BeU32`） | CRC-32/ISO-HDLC | 4 字节 |
//!
//! - 其它取值（含 CRC-8 `0x0C`、CRC-64 `0x3C`）一律**非法** →
//!   `UnsupportedOption`。
//! - 校验尾**必须恰好出现一次且位于帧尾**，不得出现在其它条目中间。解析器
//!   一旦读到 `Checksum` 键即结束本帧。**以校验尾作为帧的结尾是 v1 的不兼容
//!   边界**：未来任何允许帧以非 CRC 内容结尾的扩展都会与 v1 不兼容。
//! - `crc` 以**大端**写入（2 或 4 字节，由头字节决定），覆盖范围见 §4。
//! - 每帧的校验尾自行声明该帧使用的算法；接收方按本帧声明校验。
//!
//! ### 6.3 保留键与非法键
//!
//! 除基础键（`0x00..=0x03`）与校验尾（`0x0C`）外，其余键（含保留段
//! `0x04..=0x0B`、`0x0D..=0x0F`）在 v1 中一律**非法**。发送方**禁止**发送；
//! 接收方遇到即 `UnsupportedOption`，必须拒绝该帧。同一帧内同一已知 `key`
//! 出现两次 → `MalformedBody`。
//!
//! ## 7. 协商流程
//!
//! 协商**不是**双方的自动取小或自动合并：收到对端条件后，由**上层调用者**决定
//! 是否接受。上层拒绝（例如某个取值超出本端能力）时，直接发送 `REJECT` 并终止
//! 握手。
//!
//! ### 7.1 四项基础项
//!
//! | `key` | [`opts::BasicOpts`] 字段 | 含义 | 合法范围 |
//! | --- | --- | --- | --- |
//! | `0x00` `MaxPacketSize` | `max_packet_size` | 单个报文最大字节数（含头部） | `>= 1` |
//! | `0x01` `MaxChannelCount` | `max_channel_count` | 单连接最大同时活动 channel 数 | `>= 1` |
//! | `0x02` `MaxDockChanCount` | `max_dock_chan_count` | 单 dock 最大同时活动 channel 数 | `>= 1` |
//! | `0x03` `MaxChannelTimeout` | `max_channel_timeout` | channel 无数据后的最长存活秒数 | `>= 1` |
//!
//! 缺省值取 [`opts::BasicOpts::DEFAULT`]。任一项取值为 `0` → `MalformedBody`。
//!
//! `INVITE` 中的基础项就是发起方希望使用的取值。发起方**可以**只列出部分基础
//! 项；未列出的项由等待方按 §7.2 补全。
//!
//! ### 7.2 等待方的补全与决策（收到 `INVITE` 后）
//!
//! 等待方按以下规则生成**完整结果** `result`：
//!
//! 1. 对 `INVITE` 中**已提及**的基础项，逐字采用发起方的取值；
//! 2. 对 `INVITE` 中**未提及**的基础项，用本端取值补全（缺省为
//!    [`opts::BasicOpts::DEFAULT`]）。
//!
//! 随后把 `result` 交给上层调用者决策：
//!
//! - **接受** → 发送 `ACCEPT`，条目区**必须恰好包含全部 4 个基础项各一次**，
//!   数值为 `result[K]`。
//! - **拒绝**（例如发起方的某项取值超出本端能力）→ 发送 `REJECT` 并终止握手。
//!
//! 推荐按 `key` 升序编码，但接收方不得依赖顺序。
//!
//! ### 7.3 发起方的确认与决策（收到 `ACCEPT` 后）
//!
//! 1. `magic == K_ACCEPT_MAGIC`；若为 [`K_REJECT_MAGIC`] 则判定握手失败，其它
//!    值 → `InvalidMagic`。
//! 2. 帧级 CRC 校验已在 §4 的读取阶段完成，失败即 `ChecksumErr`。
//! 3. 条目区中基础项必须**恰好 4 个且不重复**，否则 `MalformedBody`。
//! 4. 把完整结果交给上层调用者决策：
//!    - **接受** → 发送 `CONFIRM`，条目区为这 4 个基础项；数值必须与 `ACCEPT`
//!      完全相同，**编码宽度可以不同**（按数值比较）。
//!    - **拒绝** → 发送 `REJECT` 并终止握手。
//!
//! ### 7.4 等待方的提交校验（收到 `CONFIRM` 后）
//!
//! 1. `magic == K_CONFRM_MAGIC`，帧级 CRC 已通过。
//! 2. 条目区中基础项必须**恰好 4 个且不重复**，且每项数值等于本端 `ACCEPT`
//!    中的 `result[K]`（编码宽度任意）。
//! 3. 全部一致 → 发送条目区为空（`magic` 后直接跟校验尾）的 `CONFRM`，握手
//!    成功；否则发送 `REJECT` 并关闭传输。
//!
//! ### 7.5 `REJECT`
//!
//! - 触发点：§7.2、§7.3 的上层拒绝，或 §7.4 第 2 步校验失败。
//! - v1 的 `REJECT` 条目区**必须为空**，不携带任何原因码；CRC 照常计算。
//! - 收到或发送 `REJECT` 后，双方**必须**关闭底层传输，不得重试同一次握手。
//!
//! ## 8. 状态机
//!
//! ### 8.1 发起方
//!
//! ```text
//! [Init] --发送 INVITE--> [AwaitAccept]
//!
//! [AwaitAccept]
//!   ├ 收到合法 ACCEPT 且 §7.3 通过、上层接受
//!   │     --发送 CONFIRM--> [AwaitPeerConfirm]
//!   ├ 上层拒绝 --发送 REJECT--> [Failed]
//!   └ 收到 REJECT / 校验失败 --> [Failed]
//!
//! [AwaitPeerConfirm]
//!   ├ 收到条目区为空的 CONFRM --> [Established]
//!   └ 其它 / 校验失败         --> [Failed]（按需发 REJECT 后关闭）
//! ```
//!
//! ### 8.2 等待方
//!
//! ```text
//! [Init]
//!   ├ 收到合法 INVITE、上层接受 --发送 ACCEPT--> [AwaitConfirm]
//!   ├ 收到合法 INVITE、上层拒绝 --发送 REJECT--> [Failed]
//!   └ 收到非法 INVITE ------------------------> [Failed]（按需发 REJECT 后关闭）
//!
//! [AwaitConfirm]
//!   ├ §7.4 通过 --发送空 CONFRM--> [Established]
//!   └ §7.4 失败 --发送 REJECT----> [Failed]
//! ```
//!
//! ### 8.3 时序约束
//!
//! - 握手帧严格按序，不得交错；任一端同一时刻最多有一个未完成的握手帧。
//! - 双方都不得在握手完成前发送任何数据帧。
//! - 若对端在读满一个帧之前关闭（`is_drained_closing()` 为真，或
//!   [`ReadErrTag::Closing`](abs_buff::error::ReadErrTag::Closing)）→
//!   `PeerClosed`，握手失败。
//!
//! ## 9. 错误分类
//!
//! | 变体 | 触发条件 | 处置 |
//! | --- | --- | --- |
//! | `Cancelled` | 取消令牌触发 | 终止并关闭传输；不回帧 |
//! | `RxErr(R::Err)` | 底层读错误 | 透传 |
//! | `TxErr(W::Err)` | 底层写错误 | 透传 |
//! | `InvalidMagic` | 首 4 字节不是本状态期望的 magic | 终止；不回帧 |
//! | `ChecksumErr` | CRC 不匹配 | 终止；错误帧不回帧 |
//! | `FrameTooLarge` | 累计帧长超过 `max_size` | 立即终止；不回帧 |
//! | `MalformedBody` | 宽度越界、重复键、缺少校验尾等 | 终止；不回帧 |
//! | `UnsupportedOption` | 校验尾头非 `0x1C`/`0x2C`、未知或保留键 | 发 `REJECT`（若尚未读完帧则终止） |
//! | `Inconsistent` | `ACCEPT` / `CONFIRM` 与预期不符 | 发 `REJECT` |
//! | `PeerClosed` | 帧中途对端关闭 | 终止 |
//!
//! ## 10. 取消与超时
//!
//! - 所有异步原语**必须**通过 `may_cancel_with(cancel)` 支持主动取消；对外
//!   公开的异步方法**应当**用 `gen_may_cancel_future` 封装（见 AGENTS.md
//!   纪律 4）。
//! - 取消发生在帧中途时，已读字节无法安全回退，本次握手**必须**判定失败并
//!   关闭传输；v1 **不提供**断点续读。
//! - 模块自身不实现超时；超时由调用方通过 cancel token 施加。
//!
//! ## 11. 实现要点（abs_buff 适配）
//!
//! - **定长缓冲 + 增量补齐**：帧没有长度字段，私有 `codec` 模块在缓冲不足时
//!   返回「还需多少字节」；成帧层据此逐字段补齐，直到整帧解析完成。
//! - **CRC**：帧在内部定长缓冲中成形，直接用 `crc` 的 `checksum(&[u8])`
//!   计算；校验尾头字节计入 CRC，其后的 CRC 字节不计入。
//! - **读侧**：用 `TrBuffRead::read_async(&Demand::exactly(n))` 读满定长字段，
//!   多 slice 段视图按序摊平；`n == 0` 时跳过，避免 `Demand::exactly(0)` panic。
//! - **写侧**：用 `TrBuffWrite::write_async` 借出 `SegmMut<u8>`，通过
//!   `as_segm_mut().clone_items_from_buff(..)` 写入，`Drop` 时按写入量提交。
//! - **取消**：所有读写都经 `may_cancel_with(cancel)`。
//!
//! ## 12. 对外接口
//!
//! 握手对外只暴露两个对象与它们交付的结果：
//!
//! - [`agent::HandshakeAgent`]：发起方。构造时持有 `Rx` / `Tx` 与单帧长度上限；
//!   [`agent::HandshakeAgent::initiate_handshake`] 执行完整流程。
//! - [`agent::HandshakeListener`]：等待方。构造方式相同；
//!   [`agent::HandshakeListener::accept_handshake`] 执行完整流程。
//! - 两者成功后都交付 [`agent::HandshakeEndpoint`]：协商规格
//!   （[`opts::HandshakeOpts`]）与归还的一对 `Tx` / `Rx`。
//! - 失败类型为 [`error::HandshakeError`]。
//!
//! 其余编解码、成帧与状态机实现均为私有。

