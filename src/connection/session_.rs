//! 中心解复用 / 调度循环（**尚未实现**）。
//!
//! 本模块将来承载连接内部**唯一**的驱动循环：它独占握手交付的 `Rx` / `Tx`，一侧
//! 从网络解复用帧、按 dock 对找到子流的 `ChannelOwner` 并把载荷投递进对应的接收环，
//! 另一侧从各子流的发送环取数据、切分并编帧写出。整体设计与「谁拥有什么」见
//! [`crate::connection`] 模块文档 §2。
//!
//! # 为什么不再是「读写双 session」
//!
//! 早期骨架把连接切成 `ReadSession` / `WriteSession` 两个类，各自持有**全部**通道的
//! 状态。该设计已废弃（人类决策，见 `dev-notes` §11.3）：通道状态现在分散在**每条
//! 子流自己的** `ChannelOwner` 上，循环只是它们的调度者；两个类因此没有再存在的
//! 理由，本文件里的旧骨架已随之删除。
//!
//! # 将来要落的东西（按 `dev-notes` §11.6 的顺序）
//!
//! 1. 循环的输入：网络半边（`Rx` / `Tx`）、`sync_` 里的注册表与取消令牌，以及上行
//!    通知通道（多生产者 → 本循环，见 [`crate::connection`] 模块文档 §2.1）；
//! 2. 读路径：解析帧 → 按 dock 对查 owner → 投递载荷 / 更新对端发送窗口 / 处理
//!    `PING` / `PONG`（保活 + 接收窗口通告）；
//! 3. 写路径：控制帧优先，数据帧按对端发送窗口排序；窗口耗尽或环空时 park；
//! 4. 收尾：`spawn` 后立即 `detach()`，退出走**取消令牌 + 「连接已失败」标志**
//!    （模块文档 §2.2），失败原因由 API 面读回。
//!
//! 本模块当前**没有任何实现**：保留它是为了给上述内容留一个明确的落点。
